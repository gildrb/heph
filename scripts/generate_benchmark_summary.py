def _matched_local_baseline_comparisons(
    reports: Sequence[LoadedReport],
    secrets: tuple[str, ...],
) -> list[str]:
    groups: dict[
        tuple[
            str,
            str,
            str,
            object,
            object,
            object,
            object,
            object,
            object,
            object,
            object,
            object,
            object,
        ],
        list[LoadedReport],
    ] = {}
    for report in _aggregate_eligible_reports(reports):
        if not report.cases_sha256:
            continue
        key = (
            report.benchmark_type,
            report.dataset,
            report.cases_sha256,
            report.fixed_parameters.get("top_k"),
            report.fixed_parameters.get("min_score"),
            report.fixed_parameters.get("candidate_multiplier"),
            report.fixed_parameters.get("transform_strategy"),
            report.fixed_parameters.get("embedding_model"),
            _normalized_parameter(report, "embedding_query_prefix"),
            _normalized_parameter(report, "embedding_document_prefix"),
            report.fixed_parameters.get("rerank_model"),
            report.fixed_parameters.get("hybrid_sparse_weight"),
            report.fixed_parameters.get("hybrid_dense_weight"),
        )
        groups.setdefault(key, []).append(report)

    rows: list[
        tuple[LoadedReport, LoadedReport, float, float, float, float | None, float | None]
    ] = []
    for grouped_reports in groups.values():
        by_mode: dict[str, LoadedReport] = {}
        for report in grouped_reports:
            mode = _retrieval_mode(report)
            if mode and mode not in by_mode:
                by_mode[mode] = report
        for baseline_mode in ("dense", "tfidf", "bm25"):
            baseline = by_mode.get(baseline_mode)
            if baseline is None:
                continue
            candidates = [
                report
                for mode, report in by_mode.items()
                if mode != baseline_mode and mode not in _PRIMITIVE_BASELINE_MODES
            ]
            if not candidates:
                continue
            candidate = max(
                candidates,
                key=lambda report: (
                    report.metrics.hit_rate,
                    report.metrics.mrr,
                    report.metrics.expected_recall,
                    -report.input_order,
                ),
            )
            rows.append(
                (
                    baseline,
                    candidate,
                    candidate.metrics.hit_rate - baseline.metrics.hit_rate,
                    candidate.metrics.mrr - baseline.metrics.mrr,
                    candidate.metrics.expected_recall - baseline.metrics.expected_recall,
                    _optional_delta(candidate.metrics.ndcg_at_k, baseline.metrics.ndcg_at_k),
                    _optional_delta(
                        candidate.metrics.graded_ndcg_at_k,
                        baseline.metrics.graded_ndcg_at_k,
                    ),
                )
            )

    lines = ["## Matched Local Baseline Comparisons", ""]
    if not rows:
        lines.extend(
            [
                (
                    "- No matched local retrieval-mode baseline comparisons were available. "
                    "A matched comparison requires shared benchmark type, dataset, cases hash, "
                    "top-k, min-score, candidate multiplier, transform strategy, embedding "
                    "model/query prefix, rerank model, hybrid weights, and measured query count."
                ),
                "",
            ]
        )
        return lines

    lines.extend(
        [
            (
                "- These are local retrieval-mode comparisons only. They are useful standard-RAG "
                "style baselines, but they are not Codex or Factory Droid head-to-head results."
            ),
            (
                "- Match key: benchmark type, dataset, cases SHA-256, top-k, min-score, "
                "candidate multiplier, transform strategy, embedding model/query/document "
                "prefixes, rerank model, and hybrid weights. Rows show candidate minus "
                "baseline deltas."
            ),
            "",
            (
                "| Dataset | Cases SHA-256 | Baseline | Candidate | Hit Delta | MRR Delta | "
                "Expected Recall Delta | nDCG@k Delta | Graded nDCG@k Delta | Queries |"
            ),
            "|---|---|---|---|---:|---:|---:|---:|---:|---:|",
        ]
    )
    for (
        baseline,
        candidate,
        hit_delta,
        mrr_delta,
        recall_delta,
        ndcg_delta,
        graded_ndcg_delta,
    ) in rows:
        lines.append(
            "| "
            f"{_markdown_cell(candidate.dataset, secrets)} | "
            f"{_code_cell(_short_hash(candidate.cases_sha256), secrets)} | "
            f"{_comparison_label(baseline, secrets)} | "
            f"{_comparison_label(candidate, secrets)} | "
            f"{_format_delta(hit_delta)} | "
            f"{_format_delta(mrr_delta)} | "
            f"{_format_delta(recall_delta)} | "
            f"{_format_optional_delta(ndcg_delta)} | "
            f"{_format_optional_delta(graded_ndcg_delta)} | "
            f"{candidate.measured_query_count} |"
        )
    lines.append("")
    return lines


def _same_case_frontier_comparisons(
    reports: Sequence[LoadedReport],
    secrets: tuple[str, ...],
) -> list[str]:
    groups: dict[
        tuple[str, str, str, object, object, object, object, object, object],
        list[LoadedReport],
    ] = {}
    for report in _aggregate_eligible_reports(reports):
        if not report.cases_sha256:
            continue
        key = (
            report.benchmark_type,
            report.dataset,
            report.cases_sha256,
            report.fixed_parameters.get("top_k"),
            report.fixed_parameters.get("min_score"),
            report.fixed_parameters.get("transform_strategy"),
            report.fixed_parameters.get("embedding_model"),
            _normalized_parameter(report, "embedding_query_prefix"),
            _normalized_parameter(report, "embedding_document_prefix"),
        )
        groups.setdefault(key, []).append(report)

    rows: list[tuple[LoadedReport, LoadedReport]] = []
    for grouped_reports in groups.values():
        baselines = [
            report
            for report in grouped_reports
            if (_retrieval_mode(report) or "") in _PRIMITIVE_BASELINE_MODES
        ]
        candidates = [
            report
            for report in grouped_reports
            if (_retrieval_mode(report) or "") not in _PRIMITIVE_BASELINE_MODES
        ]
        if not baselines or not candidates:
            continue
        baseline = max(baselines, key=_frontier_sort_key)
        candidate = max(candidates, key=_frontier_sort_key)
        if candidate.metrics.hit_rate < baseline.metrics.hit_rate:
            continue
        rows.append((baseline, candidate))

    lines = ["## Same-Case Frontier Comparisons", ""]
    if not rows:
        lines.extend(
            [
                (
                    "- No same-case primitive-baseline frontier comparisons were available. "
                    "A frontier comparison requires shared benchmark type, dataset, cases "
                    "hash, top-k, min-score, transform strategy, and embedding model/prefixes."
                ),
                "",
            ]
        )
        return lines

    lines.extend(
        [
            (
                "- These rows compare the strongest enhanced retrieval mode against the "
                "strongest primitive baseline on the same case file and scoring setup. "
                "Candidate-specific tuning knobs are displayed rather than hidden in the "
                "match key."
            ),
            (
                "- This is evidence against standard primitive RAG baselines only; it is "
                "not a Codex or Factory Droid head-to-head result."
            ),
            "",
            (
                "| Dataset | Cases SHA-256 | Top-k | Selected Primitive Baseline | "
                "Selected Enhanced Candidate | Hit Delta | MRR Delta | Expected Recall Delta | "
                "nDCG@k Delta | Graded nDCG@k Delta | Queries |"
            ),
            "|---|---|---:|---|---|---:|---:|---:|---:|---:|---:|",
        ]
    )
    for baseline, candidate in rows:
        ndcg_delta = _optional_delta(candidate.metrics.ndcg_at_k, baseline.metrics.ndcg_at_k)
        graded_ndcg_delta = _optional_delta(
            candidate.metrics.graded_ndcg_at_k,
            baseline.metrics.graded_ndcg_at_k,
        )
        top_k = _markdown_cell(_stable_scalar(candidate.fixed_parameters.get("top_k")), secrets)
        recall_delta = candidate.metrics.expected_recall - baseline.metrics.expected_recall
        lines.append(
            "| "
            f"{_markdown_cell(candidate.dataset, secrets)} | "
            f"{_code_cell(_short_hash(candidate.cases_sha256), secrets)} | "
            f"{top_k} | "
            f"{_frontier_label(baseline, secrets)} | "
            f"{_frontier_label(candidate, secrets)} | "
            f"{_format_delta(candidate.metrics.hit_rate - baseline.metrics.hit_rate)} | "
            f"{_format_delta(candidate.metrics.mrr - baseline.metrics.mrr)} | "
            f"{_format_delta(recall_delta)} | "
            f"{_format_optional_delta(ndcg_delta)} | "
            f"{_format_optional_delta(graded_ndcg_delta)} | "
            f"{candidate.measured_query_count} |"
        )
    lines.append("")
    return lines


def _retrieval_mode(report: LoadedReport) -> str | None:
    value = report.fixed_parameters.get("retrieval_mode")
    if isinstance(value, str) and value.strip():
        return value
    return None


def _normalized_parameter(report: LoadedReport, key: str) -> object:
    value = report.fixed_parameters.get(key)
    if value is None:
        return ""
    return value


def _frontier_sort_key(report: LoadedReport) -> tuple[float, float, float, float, float, int]:
    return (
        report.metrics.hit_rate,
        report.metrics.mrr,
        report.metrics.expected_recall,
        report.metrics.ndcg_at_k if report.metrics.ndcg_at_k is not None else -1.0,
        report.metrics.graded_ndcg_at_k if report.metrics.graded_ndcg_at_k is not None else -1.0,
        -report.input_order,
    )


def _comparison_label(report: LoadedReport, secrets: tuple[str, ...]) -> str:
    mode = _retrieval_mode(report) or "unknown"
    hit_rate = _format_metric(report.metrics.hit_rate)
    mrr = _format_metric(report.metrics.mrr)
    return f"`{_redact_text(mode, secrets)}` ({hit_rate} hit, {mrr} MRR)"


def _frontier_label(report: LoadedReport, secrets: tuple[str, ...]) -> str:
    mode = _retrieval_mode(report) or "unknown"
    parts = [f"`{_redact_text(mode, secrets)}`"]
    for key, label in (
        ("candidate_multiplier", "cm"),
        ("hybrid_dense_weight", "dense"),
        ("pseudo_feedback_weight", "prf"),
    ):
        value = report.fixed_parameters.get(key)
        if value is not None:
            parts.append(f"{label}={_redact_text(_stable_scalar(value), secrets)}")
    parts.append(f"hit={_format_metric(report.metrics.hit_rate)}")
    parts.append(f"MRR={_format_metric(report.metrics.mrr)}")
    return " ".join(parts)


def _load_enterprise_rag_leaderboard(
    leaderboard_csv: Path | None,
) -> tuple[EnterpriseRagLeaderboardRow, ...]:
    if leaderboard_csv is None:
        return ()
    path = leaderboard_csv.expanduser().resolve()
    try:
        with path.open(newline="", encoding="utf-8") as handle:
            rows = tuple(csv.DictReader(handle))
    except OSError as exc:
        raise SummaryError(
            "input_not_found",
            f"could not read EnterpriseRAG leaderboard CSV: {path}",
            "Pass an existing CSV downloaded from the official leaderboard.",
        ) from exc

    leaderboard: list[EnterpriseRagLeaderboardRow] = []
    for index, row in enumerate(rows, start=2):
        model = (row.get("model") or "").strip()
        raw_recall = (row.get("recall") or "").strip()
        if not model or not raw_recall:
            continue
        try:
            recall = float(raw_recall) / 100
        except ValueError as exc:
            raise SummaryError(
                "malformed_enterprise_rag_leaderboard",
                f"EnterpriseRAG leaderboard row {index} has non-numeric recall: {raw_recall!r}",
                "Use the official CSV with a numeric recall column.",
            ) from exc
        leaderboard.append(EnterpriseRagLeaderboardRow(model=model, recall=recall))
    if not leaderboard:
        raise SummaryError(
            "malformed_enterprise_rag_leaderboard",
            f"EnterpriseRAG leaderboard CSV has no model/recall rows: {path}",
            "Use the official CSV with model and recall columns.",
        )
    return tuple(leaderboard)


def _enterprise_rag_leaderboard_comparison(
    reports: Sequence[LoadedReport],
    leaderboard: Sequence[EnterpriseRagLeaderboardRow],
    secrets: tuple[str, ...],
) -> list[str]:
    enterprise_reports = [
        report
        for report in _aggregate_eligible_reports(reports)
        if report.benchmark_type == _ENTERPRISE_RAG_BENCHMARK_TYPE
        and report.dataset == _ENTERPRISE_RAG_DATASET
    ]
    if not enterprise_reports:
        return []

    lines = ["## Official EnterpriseRAG Recall Comparison", ""]
    if not leaderboard:
        lines.extend(
            [
                (
                    "- EnterpriseRAG reports are present, but no official leaderboard CSV "
                    "was supplied. Pass `--enterprise-rag-leaderboard-csv` to compare "
                    "document recall against the public leaderboard snapshot."
                ),
                "",
            ]
        )
        return lines

    rows: list[tuple[LoadedReport, int, int, float | None]] = []
    bm25_recall = next(
        (
            row.recall
            for row in leaderboard
            if row.model.casefold() == _ENTERPRISE_RAG_BM25_LABEL.casefold()
        ),
        None,
    )
    for report in enterprise_reports:
        all_recalls = sorted(
            [row.recall for row in leaderboard] + [report.metrics.expected_recall],
            reverse=True,
        )
        rank = all_recalls.index(report.metrics.expected_recall) + 1
        rows.append((report, rank, len(all_recalls), bm25_recall))

    lines.extend(
        [
            (
                "- This section compares document recall only against the supplied official "
                "EnterpriseRAG leaderboard CSV snapshot. It does not compare answer "
                "correctness/completeness and is not a Codex or Factory Droid head-to-head."
            ),
            (
                "- Snapshot placement is descriptive aggregate-only context; top-10 or "
                "rank-improvement claims require per-query Heph evidence, paired "
                "uncertainty, win/loss/tie counts, and public snapshot hash evidence from "
                "the claim gate."
            ),
            "",
            (
                "| Report | Retrieval Mode | Recall | Recall Rank In Snapshot | "
                f"Gap vs `{_ENTERPRISE_RAG_BM25_LABEL}` | Queries |"
            ),
            "|---|---|---:|---:|---:|---:|",
        ]
    )
    for report, rank, total, baseline_recall in rows:
        baseline_delta = (
            _format_percentage_point_delta(report.metrics.expected_recall - baseline_recall)
            if baseline_recall is not None
            else "n/a"
        )
        lines.append(
            "| "
            f"{_code_cell(report.report_id, secrets)} | "
            f"{_code_cell(_retrieval_mode(report) or 'unknown', secrets)} | "
            f"{_format_percentage(report.metrics.expected_recall)} | "
            f"{rank}/{total} | "
            f"{baseline_delta} | "
            f"{report.measured_query_count} |"
        )
    lines.append("")
    return lines


def _short_hash(value: str | None) -> str:
    if not value:
        return "unknown"
    return value[:12]


def _format_delta(value: float) -> str:
    return f"{value:+.3f}"


def _format_percentage(value: float) -> str:
    return f"{value * 100:.2f}%"


def _format_percentage_point_delta(value: float) -> str:
    return f"{value * 100:+.2f} pp"


def _optional_delta(candidate: float | None, baseline: float | None) -> float | None:
    if candidate is None or baseline is None:
        return None
    return candidate - baseline


def _format_optional_delta(value: float | None) -> str:
    if value is None:
        return "n/a"
    return _format_delta(value)


def _interpretation(reports: Sequence[LoadedReport], secrets: tuple[str, ...]) -> list[str]:
    failed_reports = [report for report in reports if report.status != "success"]
    lines = [
        "## Interpretation",
        "",
    ]
    eligible_reports = _aggregate_eligible_reports(reports)
    if eligible_reports:
        highest = max(
            eligible_reports,
            key=lambda report: (report.metrics.hit_rate, -report.input_order),
        )
        lowest = min(
            eligible_reports,
            key=lambda report: (report.metrics.hit_rate, report.input_order),
        )
        lines.extend(
            [
                (
                    "- Highest observed aggregate-eligible hit rate is "
                    f"{_format_metric(highest.metrics.hit_rate)} for "
                    f"`{_redact_text(highest.report_id, secrets)}`."
                ),
                (
                    "- Lowest observed aggregate-eligible hit rate is "
                    f"{_format_metric(lowest.metrics.hit_rate)} for "
                    f"`{_redact_text(lowest.report_id, secrets)}`."
                ),
            ]
        )
    else:
        lines.append(
            "- No aggregate-eligible hit-rate observation is available because every supplied "
            "report was excluded from aggregate statistics."
        )
    if failed_reports:
        failed_ids = ", ".join(
            f"`{_redact_text(report.report_id, secrets)}`" for report in failed_reports
        )
        lines.append(
            "- Non-success reports require follow-up before treating the benchmark set as a pass: "
            f"{failed_ids}."
        )
    else:
        lines.append(
            "- All supplied reports are marked success; continue tracking trends over time."
        )
    lines.append(
        "- Interpret latency as runtime-only context, not as a deterministic quality metric."
    )
    lines.append(
        "- These observations are not a superiority or head-to-head claim. Competitive "
        "conclusions require matched baseline reports with shared dataset hashes, case IDs, "
        "prompt/model metadata, fixed parameters, scoring formulas, and command/version metadata."
    )
    lines.append("")
    return lines


def _recommendations(reports: Sequence[LoadedReport], secrets: tuple[str, ...]) -> list[str]:
    recommendations = [
        (
            "Keep using versioned JSON reports so future summaries can validate "
            "schema compatibility."
        ),
        (
            "Compare summaries only when benchmark inputs, fixed parameters, and "
            "schema versions match."
        ),
        (
            "Treat standard-RAG, Codex, Factory Droid, or other competitive conclusions as "
            "unavailable until matched baseline evidence and shared hashes are present."
        ),
    ]
    if any(report.status != "success" for report in reports):
        recommendations.insert(
            0,
            (
                "Resolve reports marked error, threshold_failed, or "
                "reproducibility_failed before release."
            ),
        )
    if any(report.metrics.latency_ms is None for report in reports):
        recommendations.append(
            "Regenerate reports with latency fields when runtime trend analysis is needed."
        )
    if any(report.warnings for report in reports):
        recommendations.append(
            "Review warnings because they may indicate partial or degraded inputs."
        )
    lines = ["## Recommendations", ""]
    lines.extend(
        f"- {_redact_text(recommendation, secrets)}" for recommendation in recommendations
    )
    lines.append("")
    return lines


def _prompt_line(report: LoadedReport, secrets: tuple[str, ...]) -> str:
    parts: list[str] = []
    if report.prompt_path is not None:
        parts.append(f"`{_redact_text(report.prompt_path, secrets)}`")
    if report.prompt_hash is not None:
        parts.append(f"hash=`{_redact_text(report.prompt_hash, secrets)}`")
    if report.model is not None:
        parts.append(f"model=`{_redact_text(report.model, secrets)}`")
    if not parts:
        return ""
    return "- Prompt/model metadata: " + " ".join(parts)


def _merged_metric_formulas(reports: Sequence[LoadedReport]) -> dict[str, str]:
    formulas: dict[str, str] = {}
    for report in reports:
        for key, value in sorted(report.metric_formulas.items()):
            formulas.setdefault(key, value)
    return formulas


def _all_benchmark_rows(reports: Sequence[LoadedReport]) -> tuple[BenchmarkRow, ...]:
    rows: list[BenchmarkRow] = []
    for report in reports:
        rows.extend(report.benchmark_rows)
    return tuple(rows)


def _aggregate_eligible_reports(reports: Sequence[LoadedReport]) -> tuple[LoadedReport, ...]:
    return tuple(report for report in reports if report.aggregation_exclusion_reason is None)


def _visualization_notes(include_visualizations: bool) -> tuple[str, ...]:
    if not include_visualizations:
        return ()
    if importlib.util.find_spec("matplotlib") is None:
        return (
            "Visualization extras were requested but are not installed; Markdown output was "
            "generated without charts. Install with `uv sync --group visualization`.",
        )
    return (
        "Visualization extras are installed; deterministic Markdown tables remain the canonical "
        "summary output for this command.",
    )


def _mean(values: Sequence[float]) -> float:
    return sum(values) / len(values)


def _median(values: Sequence[float]) -> float:
    ordered = sorted(values)
    midpoint = len(ordered) // 2
    if len(ordered) % 2:
        return ordered[midpoint]
    return (ordered[midpoint - 1] + ordered[midpoint]) / 2


def _variance(values: Sequence[float]) -> float | None:
    if len(values) < 2:
        return 0.0 if values else None
    mean = _mean(values)
    return sum((value - mean) ** 2 for value in values) / (len(values) - 1)


def _format_metric(value: float | None) -> str:
    if value is None:
        return "n/a"
    return f"{value:.3f}"


def _inline_list(values: Sequence[str], secrets: tuple[str, ...]) -> str:
    if not values:
        return "none"
    return ", ".join(f"`{_redact_text(value, secrets)}`" for value in values)


def _markdown_cell(value: object, secrets: tuple[str, ...]) -> str:
    text = _redact_text(_stable_scalar(value), secrets)
    return text.replace("\n", " ").replace("|", r"\|")


def _code_cell(value: str, secrets: tuple[str, ...]) -> str:
    return f"`{_markdown_cell(value, secrets)}`"


def _stable_scalar(value: object) -> str:
    if value is None:
        return ""
    if isinstance(value, str):
        return value
    if isinstance(value, int | float | bool):
        return str(value)
    try:
        return json.dumps(value, ensure_ascii=False, sort_keys=True)
    except TypeError:
        return str(value)


def _secret_values_from_environment() -> tuple[str, ...]:
    values = {
        value
        for name, value in os.environ.items()
        if value
        and len(value) >= 4
        and any(marker in name.upper() for marker in _SECRET_ENV_NAME_MARKERS)
    }
    return tuple(sorted(values, key=lambda item: (-len(item), item)))


def _redact_text(text: str, secret_values: tuple[str, ...]) -> str:
    redacted = text
    for secret_value in secret_values:
        redacted = redacted.replace(secret_value, REDACTED)
    redacted = _BEARER_RE.sub("Bearer " + REDACTED, redacted)
    return _SECRET_ASSIGNMENT_RE.sub(_redact_secret_assignment, redacted)


def _redact_secret_assignment(match: re.Match[str]) -> str:
    return f"{match.group(1)}{match.group(2)}{REDACTED}"


def _build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "reports",
        nargs="+",
        type=Path,
        help="Versioned JSON benchmark reports to aggregate in explicit input order",
    )
    parser.add_argument("--output", type=Path, help="Markdown summary output path")
    parser.add_argument(
        "--visualize",
        action="store_true",
        help="Include visualization availability notes without requiring visualization extras",
    )
    parser.add_argument(
        "--enterprise-rag-leaderboard-csv",
        type=Path,
        help="Official EnterpriseRAG leaderboard CSV snapshot for recall-only comparison",
    )
    return parser


def main(argv: Sequence[str] | None = None) -> int:
    parser = _build_parser()
    args = parser.parse_args(argv)
    output_path = cast("Path | None", args.output)
    report_paths = cast("list[Path]", args.reports)
    include_visualizations = cast("bool", args.visualize)
    enterprise_rag_leaderboard_csv = cast(
        "Path | None",
        args.enterprise_rag_leaderboard_csv,
    )
    secrets = _secret_values_from_environment()
    try:
        summary = generate_markdown(
            report_paths,
            include_visualizations=include_visualizations,
            enterprise_rag_leaderboard_csv=enterprise_rag_leaderboard_csv,
        )
    except SummaryError as exc:
        print(
            "benchmark summary error "
            f"[{exc.code}]: {_redact_text(exc.message, secrets)} "
            f"Remediation: {_redact_text(exc.remediation, secrets)}",
            file=sys.stderr,
        )
        return 2
    if output_path is None:
        print(summary, end="")
        return 0
    resolved = output_path.expanduser().resolve()
    resolved.parent.mkdir(parents=True, exist_ok=True)
    resolved.write_text(summary, encoding="utf-8")
    print(f"Wrote benchmark summary to {resolved}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
