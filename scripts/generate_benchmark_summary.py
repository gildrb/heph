def _result_tables(
    reports: Sequence[LoadedReport],
    secrets: tuple[str, ...],
    visualization_notes: Sequence[str],
) -> list[str]:
    lines = [
        "## Result Tables",
        "",
        "### Aggregate Metrics",
        "",
        (
            "| Order | Report ID | Status | Type | Dataset | Hit Rate | MRR | "
            "Expected Recall | Latency (ms) | Reproducibility |"
        ),
        "|---:|---|---|---|---|---:|---:|---:|---:|---|",
    ]
    lines.extend(_aggregate_metric_row(report, secrets) for report in reports)
    lines.extend(["", "### Benchmark Metrics", ""])
    lines.extend(
        [
            (
                "| Report ID | Benchmark ID | Status | Type | Dataset | Hit Rate | MRR | "
                "Expected Recall | Latency (ms) | Queries |"
            ),
            "|---|---|---|---|---|---:|---:|---:|---:|---:|",
        ]
    )
    benchmark_rows = _all_benchmark_rows(reports)
    lines.extend(_benchmark_metric_row(row, secrets) for row in benchmark_rows)
    if not benchmark_rows:
        lines.append("| n/a | n/a | n/a | n/a | n/a | n/a | n/a | n/a | n/a | 0 |")
    if visualization_notes:
        lines.extend(["", "### Visualization", ""])
        lines.extend(f"- {_redact_text(note, secrets)}" for note in visualization_notes)
    lines.append("")
    return lines


def _per_benchmark_analysis(
    reports: Sequence[LoadedReport],
    secrets: tuple[str, ...],
) -> list[str]:
    lines = ["## Per-Benchmark Analysis", ""]
    for report in reports:
        lines.extend(
            [
                f"### {_redact_text(report.report_id, secrets)}",
                "",
                f"- Status: `{_redact_text(report.status, secrets)}`",
                (
                    "- Aggregate metrics: "
                    f"hit_rate={_format_metric(report.metrics.hit_rate)}, "
                    f"mrr={_format_metric(report.metrics.mrr)}, "
                    "expected_recall="
                    f"{_format_metric(report.metrics.expected_recall)}, "
                    f"latency_ms={_format_metric(report.metrics.latency_ms)}"
                ),
                (
                    "- Fixed parameters: "
                    f"`{_markdown_cell(_stable_scalar(report.fixed_parameters), secrets)}`"
                ),
            ]
        )
        prompt_line = _prompt_line(report, secrets)
        if prompt_line:
            lines.append(prompt_line)
        if report.threshold_failures:
            lines.append("- Threshold failures:")
            lines.extend(
                f"  - {_redact_text(failure, secrets)}" for failure in report.threshold_failures
            )
        if report.errors:
            lines.append("- Errors:")
            lines.extend(f"  - {_redact_text(error, secrets)}" for error in report.errors)
        if report.warnings:
            lines.append("- Warnings:")
            lines.extend(f"  - {_redact_text(warning, secrets)}" for warning in report.warnings)
        if report.benchmark_rows:
            lines.append("- Benchmark entries:")
            lines.extend(
                (
                    "  - "
                    f"`{_redact_text(row.benchmark_id, secrets)}` status="
                    f"`{_redact_text(row.status, secrets)}` queries={row.per_query_count}"
                )
                for row in report.benchmark_rows
            )
        lines.append("")
    return lines


def _statistical_analysis(
    reports: Sequence[LoadedReport],
    secrets: tuple[str, ...],
) -> list[str]:
    rows = _all_benchmark_rows(reports)
    sample_basis = (
        f"{len(reports)} report(s); {len(rows)} benchmark row(s). "
        "Calculations use aggregate report metrics so every report contributes once."
    )
    metric_values = {
        "Hit Rate": [report.metrics.hit_rate for report in reports],
        "MRR": [report.metrics.mrr for report in reports],
        "Expected Recall": [report.metrics.expected_recall for report in reports],
        "Latency (ms)": [
            report.metrics.latency_ms
            for report in reports
            if report.metrics.latency_ms is not None
        ],
    }
    lines = [
        "## Statistical Analysis",
        "",
        f"- Sample size: {_redact_text(sample_basis, secrets)}",
        (
            "- Comparison basis: deterministic aggregate metrics supplied in the input reports; "
            "no external baselines are invented."
        ),
        (
            "- Limitations: descriptive means and medians are not significance tests, and missing "
            "latency values are excluded only from latency statistics."
        ),
        "",
        "| Metric | Count | Mean | Median | Min | Max |",
        "|---|---:|---:|---:|---:|---:|",
    ]
    for name, raw_values in metric_values.items():
        values = [value for value in raw_values if value is not None]
        lines.append(
            "| "
            f"{_markdown_cell(name, secrets)} | "
            f"{len(values)} | "
            f"{_format_metric(_mean(values) if values else None)} | "
            f"{_format_metric(_median(values) if values else None)} | "
            f"{_format_metric(min(values) if values else None)} | "
            f"{_format_metric(max(values) if values else None)} |"
        )
    lines.append("")
    return lines


def _interpretation(reports: Sequence[LoadedReport], secrets: tuple[str, ...]) -> list[str]:
    failed_reports = [report for report in reports if report.status != "success"]
    best = max(reports, key=lambda report: (report.metrics.hit_rate, -report.input_order))
    weakest = min(reports, key=lambda report: (report.metrics.hit_rate, report.input_order))
    lines = [
        "## Interpretation",
        "",
        (
            f"- Highest observed hit rate is {_format_metric(best.metrics.hit_rate)} "
            f"for `{_redact_text(best.report_id, secrets)}`."
        ),
        (
            f"- Lowest observed hit rate is {_format_metric(weakest.metrics.hit_rate)} "
            f"for `{_redact_text(weakest.report_id, secrets)}`."
        ),
    ]
    if failed_reports:
        failed_ids = ", ".join(
            f"`{_redact_text(report.report_id, secrets)}`" for report in failed_reports
        )
        lines.append(
            "- Non-success reports require follow-up before treating the benchmark set as a pass: "
            f"{failed_ids}."
        )
    else:
        lines.append(
            "- All supplied reports are marked success; continue tracking trends over time."
        )
    lines.append(
        "- Interpret latency as runtime-only context, not as a deterministic quality metric."
    )
    lines.append("")
    return lines


def _recommendations(reports: Sequence[LoadedReport], secrets: tuple[str, ...]) -> list[str]:
    recommendations = [
        (
            "Keep using versioned JSON reports so future summaries can validate "
            "schema compatibility."
        ),
        (
            "Compare summaries only when benchmark inputs, fixed parameters, and "
            "schema versions match."
        ),
    ]
    if any(report.status != "success" for report in reports):
        recommendations.insert(
            0,
            (
                "Resolve reports marked error, threshold_failed, or "
                "reproducibility_failed before release."
            ),
        )
    if any(report.metrics.latency_ms is None for report in reports):
        recommendations.append(
            "Regenerate reports with latency fields when runtime trend analysis is needed."
        )
    if any(report.warnings for report in reports):
        recommendations.append(
            "Review warnings because they may indicate partial or degraded inputs."
        )
    lines = ["## Recommendations", ""]
    lines.extend(
        f"- {_redact_text(recommendation, secrets)}" for recommendation in recommendations
    )
    lines.append("")
    return lines


def _prompt_line(report: LoadedReport, secrets: tuple[str, ...]) -> str:
    parts: list[str] = []
    if report.prompt_path is not None:
        parts.append(f"`{_redact_text(report.prompt_path, secrets)}`")
    if report.prompt_hash is not None:
        parts.append(f"hash=`{_redact_text(report.prompt_hash, secrets)}`")
    if report.model is not None:
        parts.append(f"model=`{_redact_text(report.model, secrets)}`")
    if not parts:
        return ""
    return "- Prompt/model metadata: " + " ".join(parts)


def _merged_metric_formulas(reports: Sequence[LoadedReport]) -> dict[str, str]:
    formulas: dict[str, str] = {}
    for report in reports:
        for key, value in sorted(report.metric_formulas.items()):
            formulas.setdefault(key, value)
    return formulas


def _all_benchmark_rows(reports: Sequence[LoadedReport]) -> tuple[BenchmarkRow, ...]:
    rows: list[BenchmarkRow] = []
    for report in reports:
        rows.extend(report.benchmark_rows)
    return tuple(rows)


def _visualization_notes(include_visualizations: bool) -> tuple[str, ...]:
    if not include_visualizations:
        return ()
    if importlib.util.find_spec("matplotlib") is None:
        return (
            "Visualization extras were requested but are not installed; Markdown output was "
            "generated without charts. Install with `uv sync --extra visualization`.",
        )
    return (
        "Visualization extras are installed; deterministic Markdown tables remain the canonical "
        "summary output for this command.",
    )


def _mean(values: Sequence[float]) -> float:
    return sum(values) / len(values)


def _median(values: Sequence[float]) -> float:
    ordered = sorted(values)
    midpoint = len(ordered) // 2
    if len(ordered) % 2:
        return ordered[midpoint]
    return (ordered[midpoint - 1] + ordered[midpoint]) / 2


def _format_metric(value: float | None) -> str:
    if value is None:
        return "n/a"
    return f"{value:.3f}"


def _inline_list(values: Sequence[str], secrets: tuple[str, ...]) -> str:
    if not values:
        return "none"
    return ", ".join(f"`{_redact_text(value, secrets)}`" for value in values)


def _markdown_cell(value: object, secrets: tuple[str, ...]) -> str:
    text = _redact_text(_stable_scalar(value), secrets)
    return text.replace("\n", " ").replace("|", r"\|")


def _code_cell(value: str, secrets: tuple[str, ...]) -> str:
    return f"`{_markdown_cell(value, secrets)}`"


def _stable_scalar(value: object) -> str:
    if value is None:
        return ""
    if isinstance(value, str):
        return value
    if isinstance(value, int | float | bool):
        return str(value)
    try:
        return json.dumps(value, ensure_ascii=False, sort_keys=True)
    except TypeError:
        return str(value)


def _secret_values_from_environment() -> tuple[str, ...]:
    values = {
        value
        for name, value in os.environ.items()
        if value
        and len(value) >= 4
        and any(marker in name.upper() for marker in _SECRET_ENV_NAME_MARKERS)
    }
    return tuple(sorted(values, key=lambda item: (-len(item), item)))


def _redact_text(text: str, secret_values: tuple[str, ...]) -> str:
    redacted = text
    for secret_value in secret_values:
        redacted = redacted.replace(secret_value, REDACTED)
    redacted = _BEARER_RE.sub("Bearer " + REDACTED, redacted)
    return _SECRET_ASSIGNMENT_RE.sub(_redact_secret_assignment, redacted)


def _redact_secret_assignment(match: re.Match[str]) -> str:
    return f"{match.group(1)}{match.group(2)}{REDACTED}"


def _build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "reports",
        nargs="+",
        type=Path,
        help="Versioned JSON benchmark reports to aggregate in explicit input order",
    )
    parser.add_argument("--output", type=Path, help="Markdown summary output path")
    parser.add_argument(
        "--visualize",
        action="store_true",
        help="Include visualization availability notes without requiring visualization extras",
    )
    return parser


def main(argv: Sequence[str] | None = None) -> int:
    parser = _build_parser()
    args = parser.parse_args(argv)
    output_path = cast("Path | None", args.output)
    report_paths = cast("list[Path]", args.reports)
    include_visualizations = cast("bool", args.visualize)
    secrets = _secret_values_from_environment()
    try:
        summary = generate_markdown(
            report_paths,
            include_visualizations=include_visualizations,
        )
    except SummaryError as exc:
        print(
            "benchmark summary error "
            f"[{exc.code}]: {_redact_text(exc.message, secrets)} "
            f"Remediation: {_redact_text(exc.remediation, secrets)}",
            file=sys.stderr,
        )
        return 2
    if output_path is None:
        print(summary, end="")
        return 0
    resolved = output_path.expanduser().resolve()
    resolved.parent.mkdir(parents=True, exist_ok=True)
    resolved.write_text(summary, encoding="utf-8")
    print(f"Wrote benchmark summary to {resolved}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
